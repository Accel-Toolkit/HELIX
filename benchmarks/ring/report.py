#!/usr/bin/env python3
"""The ring-mode benchmark cases as a page: one table per level, read from
``benchmarks/ring/cases.yaml``.

    python benchmarks/ring/report.py            # writes the manual's case list
    python benchmarks/ring/report.py --check    # exit 1 when that page is not current
    python benchmarks/ring/report.py --dev      # with dev/cases.yaml, to dev/REPORT_<date>.md

The manual's page (``docs/manual/12_validation/07_ring_cases.md``) lists the
public cases; the dev report adds the cases on private lattices and stays
in the dev-only folder.  A test keeps the manual's page current.
"""
from __future__ import annotations

import argparse
import datetime as _dt
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CASES = ROOT / "benchmarks" / "ring" / "cases.yaml"
DEV_CASES = ROOT / "benchmarks" / "ring" / "dev" / "cases.yaml"
PAGE = ROOT / "docs" / "manual" / "12_validation" / "07_ring_cases.md"
LEVELS = (("L0", "Analytic results and bookkeeping"), ("L1", "Element maps and ring optics"),
          ("L2", "Single particles over many turns, the ramp"), ("L3", "Space charge"),
          ("L4", "Injection"),
          ("L5", "Many turns: losses and space charge through transition, painting"),
          ("performance", "Speed"))
#: tests and scripts left out of public releases (their data are private or unlicensed)
DEV_PATHS = ("tests/ring/dev/", "benchmarks/ring/dev/")


def _cell(v) -> str:
    """A table cell: one line, pipes escaped."""
    return " ".join(str(v).split()).replace("|", "\\|") if v not in (None, "") else "—"


def _load(path: Path) -> list:
    import yaml
    return yaml.safe_load(path.read_text(encoding="utf-8"))["cases"]


def render(rows: list, *, title: str, intro: str) -> str:
    out = [f"# {title}", "", intro, ""]
    known = {k for k, _ in LEVELS}
    for key, heading in LEVELS + (("other", "Other"),):
        sel = [r for r in rows if (r.get("level") if r.get("level") in known else "other") == key]
        if not sel:
            continue
        out += [f"## {heading}", "", "| Case | What | Reference | Tolerance and result | Test |",
                "|---|---|---|---|---|"]
        for r in sel:
            test = r.get("test")
            cell = f"`{_cell(test)}`" if test else "—"
            if test and str(test).startswith(DEV_PATHS):
                cell += " — a developers' check, not distributed with HELIX"
            tol = r.get("tolerance") or (f"status: {r['status']}" if r.get("status") else None)
            out.append("| " + " | ".join((
                f"`{r['id']}` ({r.get('milestone', '—')})", _cell(r.get("what")),
                _cell(r.get("reference")), _cell(tol), cell)) + " |")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def public_page() -> str:
    return render(_load(CASES), title="Ring-mode benchmark cases", intro=(
        "Every ring-mode benchmark case, by level: what it checks, its reference, the tolerance "
        "with the result measured, and the test that keeps it — the list in "
        "`benchmarks/ring/cases.yaml`, from which this page is generated "
        "(`python benchmarks/ring/report.py`).  The results are discussed in "
        "[Ring-mode benchmarks](06_ring_benchmarks.md); the reference codes are named there as "
        "here, by letter."))


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--dev", action="store_true")
    a = ap.parse_args(argv)
    if a.dev:
        if not DEV_CASES.is_file():
            print("no dev cases here (a public release leaves them out)")
            return 1
        rows = _load(CASES) + _load(DEV_CASES)
        day = _dt.date.today().isoformat()
        text = render(rows, title=f"Ring-mode benchmark report, {day} (dev)", intro=(
            "The public cases and those on private lattices (`benchmarks/ring/dev/cases.yaml`), "
            "generated by `python benchmarks/ring/report.py --dev`.  Dev only: this folder is "
            "left out of public releases."))
        dst = DEV_CASES.parent / f"REPORT_{day}.md"
        dst.write_text(text, encoding="utf-8")
        print(dst)
        return 0
    text = public_page()
    if a.check:
        cur = PAGE.read_text(encoding="utf-8") if PAGE.is_file() else ""
        if cur != text:
            print(f"{PAGE.relative_to(ROOT)} is not current: run python benchmarks/ring/report.py")
            return 1
        return 0
    PAGE.write_text(text, encoding="utf-8")
    print(PAGE)
    return 0


if __name__ == "__main__":
    sys.exit(main())
