def test_chart_progress_reports_chunks(solver):
    calls: list = []
    r, y, G = solver.chart(1.475, steps=100, l_modes=(2,),
                           progress=lambda i, n: calls.append((i, n)))
    assert G.shape == (y.size, r.size)
    assert calls, "progress was never called"
    assert calls[-1][0] == calls[-1][1]        # final chunk == n_chunks
    assert [c[0] for c in calls] == list(range(1, len(calls) + 1))
