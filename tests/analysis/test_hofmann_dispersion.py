def test_batch_matches_scalar(solver):
    """growth_rate_batch == a growth_rate loop (the per-row scan grids
    differ from the scalar path by last-ulp rounding only)."""
    rng = np.random.default_rng(3)
    R = rng.uniform(0.1, 3.0, 50)
    Y = rng.uniform(0.15, 0.95, 50)
    for eps in (1.0, 1.475, 5.73):
        g_batch = solver.growth_rate_batch(R, Y, eps)
        g_scalar = np.array([
            solver.growth_rate(R=float(r), Y=float(y), eps_ratio=eps)
            for r, y in zip(R, Y)
        ])
        np.testing.assert_allclose(g_batch, g_scalar, rtol=1e-9, atol=1e-9)


