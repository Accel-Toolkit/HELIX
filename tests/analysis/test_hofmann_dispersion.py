# =============================================================================
# 1. Printed-equation anchors: iso-limit reduction to Eqs. (37)/(42)/(46)
# =============================================================================

def _D3e_iso_eq37(s, sp2):
    """Hofmann Eq. (37): l=3 even isotropic dispersion function.

    Leading 8; S^2 block 12 S^2/(9-s) (the four Eq. (36) residues collapse
    to (-4+4)/(1-s) + (60+36)/(9-s)); S^4 term -4 S^4 s(3-s) /
    [(9-s)^2 (1-s)^2] (manuscript App. A, Eq. (A6))."""
    return (8.0 + 12.0 * sp2 / (9.0 - s)
            - 4.0 * sp2 ** 2 * s * (3.0 - s)
            / ((9.0 - s) ** 2 * (1.0 - s) ** 2))


def _D4e_iso_eq42(s, sp2):
    """Hofmann Eq. (42): l=4 even isotropic dispersion function, with the
    sp^4-block sign CORRECTED to +34/(16-s)^2 - 2/(4-s)^2.

    The journal prints Eq. (42) with -34/(16-s)^2 + 2/(4-s)^2, which is
    inconsistent with Eq. (41)'s -sp^4; Eq. (43)'s roots (the arbiter,
    ``test_eq43_roots_fix_the_l4_even_sp4_sign``) show Eq. (42) carries
    the typo, so the sign here is flipped from the printed page."""
    g16, g4 = 16.0 - s, 4.0 - s
    return (16.0 + sp2 * (44.0 / g16 - 4.0 / g4)
            + sp2 ** 2 * (34.0 / g16 ** 2 - 2.0 / g4 ** 2)
            + sp2 ** 3 * (6.0 / g16 ** 3 - 2.0 / (g16 * g4 ** 2)
                          + 4.0 / (g16 ** 2 * g4)))


def _D4o_iso_eq46(s, sp2):
    """Hofmann Eq. (46): l=4 odd isotropic dispersion function."""
    g16, g4 = 16.0 - s, 4.0 - s
    return (16.0 + sp2 * (4.0 / g4 + 20.0 / g16)
            + sp2 ** 2 * (4.0 / g16 ** 2 + 4.0 / (g16 * g4)))


@pytest.mark.parametrize("label,D_fn,ref_fn", [
    ("l3_even/Eq37", l3_even_D, _D3e_iso_eq37),
    ("l4_even/Eq42corrected", l4_even_D, _D4e_iso_eq42),
    ("l4_odd/Eq46", l4_odd_D, _D4o_iso_eq46),
])
def test_iso_limit_reduces_to_printed_equations(label, D_fn, ref_fn):
    """At alpha = eta = 1 each branch equals Hofmann's isotropic form to
    machine precision (measured max rel err ~4e-16).  l3_even (Eq. 37) and
    l4_odd (Eq. 46) match the printed page; l4_even matches Eq. (42) with
    the sp^4-block sign corrected per Eq. (43) (see the arbiter test)."""
    rng = np.random.default_rng(0)
    s_vals = -np.exp(rng.uniform(np.log(1e-3), np.log(200.0), 40))
    sp2_vals = rng.uniform(0.1, 5.0, 8)
    for s in s_vals:
        for sp2 in sp2_vals:
            got = D_fn(s, 1.0, 1.0, sp2)
            want = ref_fn(s, sp2)
            assert got == pytest.approx(want, rel=1e-12), (
                f"{label} fails iso reduction at s={s}, sp2={sp2}: "
                f"{got!r} vs printed {want!r}"
            )


def test_l3_odd_equals_even_at_isotropy():
    """The p. 4719 interchange is the identity at alpha = h = 1."""
    for s in (-0.5, -4.0, -20.0):
        for sp2 in (0.5, 2.0, 6.0):
            assert l3_odd_D(s, 1.0, 1.0, sp2) == pytest.approx(
                l3_even_D(s, 1.0, 1.0, sp2), rel=1e-14)


def test_eq43_roots_fix_the_l4_even_sp4_sign():
    """Hofmann Eq. (43)'s closed-form roots settle the Eq. (41)/(42) sign
    conflict (ported from the PRAB_Hofmann reference).

    The journal prints Eq. (41) with -sp^4 AND Eq. (42) with
    -34/(16-s)^2 + 2/(4-s)^2. Those two are mutually inconsistent, so one
    is misprinted. Eq. (43) gives the five closed-form isotropic roots and
    is the independent arbiter: they zero the +34/(16-s)^2 - 2/(4-s)^2 form
    (which factors as -16*prod(s - r_i)) but not the printed one. So
    Eq. (42) carries the typo and Eq. (41)'s printed -sp^4 is correct. An
    earlier version of HELIX adopted +sp^4 because it reduced to the
    *printed* Eq. (42) — validating against the misprinted equation. This
    pins the resolution so the l=4-even sp^4 sign cannot silently revert."""
    sym = pytest.importorskip("sympy")
    s, p = sym.symbols("s p")

    def D42(sign):
        return (16 + p * (sym.Integer(44) / (16 - s) - sym.Integer(4) / (4 - s))
                + p**2 * (sign * 34 / (16 - s)**2 - sign * 2 / (4 - s)**2)
                + p**3 * (6 / (16 - s)**3 - 2 / ((16 - s) * (4 - s)**2)
                          + 4 / ((16 - s)**2 * (4 - s))))

    roots = [16 + p,
             (20 + p + sym.sqrt((20 + p)**2 - 4 * (64 - 2 * p))) / 2,
             (20 + p - sym.sqrt((20 + p)**2 - 4 * (64 - 2 * p))) / 2,
             (40 + p + sym.sqrt((40 + p)**2 - 8 * (128 + 10 * p))) / 4,
             (40 + p - sym.sqrt((40 + p)**2 - 8 * (128 + 10 * p))) / 4]

    # (i) the corrected form is satisfied by every Eq. (43) root; printed is not
    assert all(sym.simplify(sym.together(D42(+1).subs(s, r))) == 0 for r in roots)
    assert not all(sym.simplify(sym.together(D42(-1).subs(s, r))) == 0 for r in roots)

    # (ii) only the corrected form's numerator is exactly the root product (= -16)
    prod = sym.expand(sym.prod([s - r for r in roots]))
    num_ok, _ = sym.fraction(sym.together(D42(+1)))
    q = sym.cancel(sym.expand(num_ok) / prod)
    assert sym.simplify(sym.diff(q, s)) == 0        # s-independent quotient
    assert sym.simplify(q + 16) == 0                # equal to -16

    # (iii) HELIX's l4_even_D (now -sp^4) reduces to the corrected form at iso
    for sv in (-0.3, -2.0, -7.0, -25.0):
        for pv in (0.4, 1.5, 4.0):
            got = float(l4_even_D(sv, 1.0, 1.0, pv))
            want = float(D42(+1).subs({s: sv, p: pv}))
            assert got == pytest.approx(want, rel=1e-12)


