"""Trust anchors for the corrected Hofmann dispersion solver.

Three independent layers, none of which is a copy of the implementation:

1. **Printed-equation anchors** — the branch functions at the isotropic
   point ``alpha = eta = 1`` must equal Hofmann (1998)'s own published
   isotropic closed forms Eqs. (37)/(42)/(46), transcribed here as
   standalone reference expressions (external ground truth; house rule 3).
2. **Off-isotropic identity pins** — Hofmann's Eq. (24) pairing, the
   p. 4716 emittance identity ``h^2/alpha``, Eq. (5), the gscale
   convention, and the p. 4719 odd-branch interchange, at points where the
   historical coordinate-map defects were visible.  These are the checks
   the iso-limit structurally cannot make (every defect they catch
   vanishes at ``alpha = h = 1``).  Ported from the source manuscript
   package's ``tests/test_hofmann_identities.py``.
3. **Golden cross-repo pins** — 20 chart points spanning both flip
   branches with every branch active somewhere, generated by the source
   package's solver (``PRAB_Hofmann/analysis/dispersion.py``,
   fingerprint 043d0944a1).  On the reference platform (macOS/arm64,
   numpy>=1.24) the HELIX port reproduces them BITWISE; the tolerance
   below allows only last-ulp libm variation on other platforms and any
   failure means the physics drifted from the source package.
"""
