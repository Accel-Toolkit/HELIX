@pytest.mark.parametrize("R,eps", CASES)
def test_emittance_identity_h2_over_alpha(R, eps):
    """Hofmann p.4716: eps_x/eps_y = h^2/alpha, for the plane he calls x.

    Which physical plane is Hofmann's "x" is fixed by h >= 1, so the
    target is eps_z/eps_x when the longitudinal plane carries the larger
    envelope and its reciprocal otherwise."""
    alpha, h, _, _, _ = map_to_pre_grid(np.array([R]), np.array([0.5]), eps)
    alpha, h = alpha.item(), h.item()
    assert h >= 1.0, "Hofmann's h = a/b is defined >= 1 (Eq. 24)"
    flipped = np.sqrt(R / eps) < 1.0
    target = eps if flipped else 1.0 / eps
    assert h * h / alpha == pytest.approx(target, rel=1e-12)


@pytest.mark.parametrize("R,eps", CASES)
@pytest.mark.parametrize("Y", [0.3, 0.55, 0.8, 0.95])
def test_sp2_matches_eq5(R, eps, Y):
    """Eq. (5) inverted: sp2 = (1+h)(1-eta_dep^2)/eta_dep^2 for whichever
    plane Hofmann labels x."""
    alpha, h, sp2, _, _ = map_to_pre_grid(np.array([R]), np.array([Y]), eps)
    h, sp2 = h.item(), sp2.item()
    if np.sqrt(R / eps) >= 1.0:                       # Hofmann-x == transverse
        expect = (1.0 + h) * (1.0 - Y * Y) / (Y * Y)
    else:                                             # Hofmann-x == longitudinal
        expect = (1.0 + h) * (1.0 - Y * Y) / (h * R * R * Y * Y)
    assert sp2 == pytest.approx(expect, rel=1e-12)


@pytest.mark.parametrize("Y", [0.3, 0.6, 0.9])
def test_isotropic_point_unchanged(Y):
    """At R = eps = 1 the map must return the textbook isotropic values."""
    alpha, h, sp2, _, gs = map_to_pre_grid(np.array([1.0]), np.array([Y]), 1.0)
    assert alpha.item() == pytest.approx(1.0, rel=1e-14)
    assert h.item() == pytest.approx(1.0, rel=1e-14)
    assert sp2.item() == pytest.approx(2.0 * (1 - Y * Y) / (Y * Y), rel=1e-12)
    assert gs.item() == pytest.approx(Y, rel=1e-14)


@pytest.mark.parametrize("R,eps", CASES)
@pytest.mark.parametrize("Y", [0.4, 0.75])
def test_gscale_is_active_plane_depression(R, eps, Y):
    """gscale converts sqrt(-s) to Im(omega)/nu_0x for the plane setting s."""
    _, _, _, _, gs = map_to_pre_grid(np.array([R]), np.array([Y]), eps)
    flipped = np.sqrt(R / eps) < 1.0
    assert gs.item() == pytest.approx(R * Y if flipped else Y, rel=1e-12)


@pytest.mark.parametrize("alpha,h,sp2", [
    (0.8, 1.4, 2.0), (1.7, 2.2, 0.7), (0.45, 3.1, 4.5), (2.6, 1.05, 1.3),
])
@pytest.mark.parametrize("s", [-0.5, -3.0, -12.0])
def test_odd_branch_rescales_sp2_and_s(alpha, h, sp2, s):
    """p.4719: the odd interchange acts on Eqs. (24) AND (25) — sp2 and s
    are normalised to nu_x^2, so the interchange rescales both.  Holding
    sp2 or s fixed is the historical defect this pins."""
    got = l3_odd_D(s, alpha, h, sp2)
    want = l3_even_D(s / alpha ** 2, 1.0 / alpha, 1.0 / h, sp2 / alpha ** 2)
    assert got == pytest.approx(want, rel=1e-12)


@pytest.mark.parametrize("eps,Y", [
    (5.0, 0.35), (5.0, 0.30), (3.0, 0.40), (8.5, 0.30), (1.5, 0.45),
])
def test_physical_growth_continuous_across_seam(eps, Y):
    """gamma/nu_0x must be continuous across the h = 1 interchange
    boundary: the internal variables jump by the relabelling factors, but
    the observable growth rate is invariant."""
    s = DispersionSolver()
    lo = s.growth_rate(R=eps - 1e-6, Y=Y, eps_ratio=eps, l_modes=(2, 3, 4))
    hi = s.growth_rate(R=eps + 1e-6, Y=Y, eps_ratio=eps, l_modes=(2, 3, 4))
    scale = max(lo, hi)
    if scale < 1e-3:
        pytest.skip("no resolved growth at this seam point")
    assert abs(hi - lo) / scale < 1e-5


def test_seam_internal_variables_jump_by_the_relabelling_factors():
    """Pin HOW the internal variables jump at h = 1, so the relabelling
    stays explicit rather than looking like a broken map."""
    eps, Y = 1.5, 0.5
    a_lo, h_lo, sp2_lo, _, gs_lo = map_to_pre_grid(
        np.array([eps - 1e-6]), np.array([Y]), eps)
    a_hi, h_hi, sp2_hi, _, gs_hi = map_to_pre_grid(
        np.array([eps + 1e-6]), np.array([Y]), eps)
    R = eps
    assert h_lo.item() == pytest.approx(1.0, abs=1e-5)
    assert h_hi.item() == pytest.approx(1.0, abs=1e-5)
    assert a_lo.item() == pytest.approx(1.0 / R, rel=1e-5)     # flipped frame
    assert a_hi.item() == pytest.approx(R, rel=1e-5)           # unflipped
    assert sp2_lo.item() / sp2_hi.item() == pytest.approx(1.0 / R ** 2,
                                                          rel=1e-5)
    assert gs_lo.item() / gs_hi.item() == pytest.approx(R, rel=1e-5)


