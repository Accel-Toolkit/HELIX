"""Making the RFQ_CELL θs operand LIVE against the deck's own lengths.

The headline tests here run on the SYNTHETIC demo deck and therefore on
any checkout — they need no TraceWin reference data.  That matters,
because the derivation being validated is the one that closes a 7 % gap
on PXIE, and it would be worthless if its only evidence were the deck it
was invented on.

The PXIE tests below skip cleanly wherever that project is absent.
"""
from __future__ import annotations

import pathlib
import warnings

import numpy as np
import pytest

from linac_gen.core.particle import H_MINUS, PROTON
from linac_gen.elements.rfq_cell import RfqCell
from linac_gen.io.rfq_phase_repair import (
    DEFAULT_MIN_A10,
    RfqPhaseInconsistencyWarning,
    derived_phases,
    inconsistent_phase_cells,
    repair_rfq_phases,
)
from linac_gen.io.tracewin_parser import parse_tracewin

DEMO = (pathlib.Path(__file__).resolve().parents[2]
        / "examples" / "rfq_demo" / "rfq_demo.dat")


def _demo():
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        lat, _ = parse_tracewin(str(DEMO))
    return lat


def _cells(lat):
    return [e for e in lat.elements if isinstance(e, RfqCell)]


# ---------------------------------------------------------------- demo


def test_derivation_reproduces_an_independent_decks_phase_ramp():
    """The core claim, on a deck it was NOT invented on.

    ``examples/rfq_demo`` is generated by make_rfq_demo.py from textbook
    relations with its own φs ramp (−90 → −28).  Deriving φs from that
    deck's cell LENGTHS alone — never reading its φs column — must
    reproduce that ramp.  Zero free parameters.
    """
    lat = _demo()
    cells = _cells(lat)
    phi, valid = derived_phases(lat, PROTON.mass, PROTON.charge, 352.21)
    card = np.array([c.phi_s_deg for c in cells])
    A10 = np.array([c.A10 for c in cells])
    m = valid & (A10 >= DEFAULT_MIN_A10)
    assert m.sum() > 50, f"only {m.sum()} derivable cells — deck changed?"
    d = (phi - card)[m]
    # A few degrees: the closed form drops the transit-time factor.
    assert abs(d.mean()) < 6.0, d.mean()
    assert d.std() < 3.0, d.std()
    assert np.abs(d).max() < 15.0, np.abs(d).max()


def test_no_false_positives_on_the_demo_deck():
    """A self-consistent deck must be flagged ZERO times — including its
    legitimately unmodulated −90° shaper and matcher cells."""
    lat = _demo()
    assert inconsistent_phase_cells(
        lat, PROTON.mass, PROTON.charge, 352.21) == []


def test_repair_is_a_no_op_on_a_consistent_deck():
    lat = _demo()
    before = [c.phi_s_deg for c in _cells(lat)]
    with warnings.catch_warnings():
        warnings.simplefilter("error")          # must not even warn
        assert repair_rfq_phases(
            lat, PROTON.mass, PROTON.charge, 352.21) == []
    assert [c.phi_s_deg for c in _cells(lat)] == before


def test_detection_is_read_only():
    lat = _demo()
    before = [c.phi_s_deg for c in _cells(lat)]
    inconsistent_phase_cells(lat, PROTON.mass, PROTON.charge, 352.21)
    assert [c.phi_s_deg for c in _cells(lat)] == before


def test_matcher_boundary_does_not_manufacture_a_finding():
    """The card before an exit matcher is NOT derivable: the matcher's
    length is set by geometry, not synchronism, so ΔW across its
    predecessor is meaningless.  Regression — before the successor check
    this produced a spurious θs = −90 for the demo's good −28 card."""
    lat = _demo()
    cells = _cells(lat)
    phi, valid = derived_phases(lat, PROTON.mass, PROTON.charge, 352.21)
    matchers = [i for i, c in enumerate(cells) if c.A10 == 0.0]
    assert matchers, "demo deck should carry unmodulated matcher cells"
    for i in matchers:
        assert not valid[i], f"matcher cell {i} must not be derivable"
        if i > 0:
            assert not valid[i - 1], (
                f"cell {i-1} precedes a matcher — not derivable")


def test_above_crest_deck_is_not_flagged_wholesale():
    """cos θs is EVEN, so the derivation fixes only |θs|.  Mirroring a
    consistent deck's θs about zero must not turn every card into a
    finding — otherwise any above-crest design would be unusable."""
    lat = _demo()
    for c in _cells(lat):
        c.phi_s_deg = -c.phi_s_deg
    bad = inconsistent_phase_cells(lat, PROTON.mass, PROTON.charge,
                                   352.21)
    assert bad == [], [(f.index, f.phi_card_deg) for f in bad]


def test_repair_without_anchors_warns_and_uses_raw_derivation():
    """A run of bad cards with no consistent predecessor must not
    silently invent an offset."""
    lat = _demo()
    cells = _cells(lat)
    hit = [i for i, c in enumerate(cells) if c.A10 >= DEFAULT_MIN_A10]
    assert hit
    # Break the very FIRST modulated cards.  Everything before them is
    # below the A10 threshold, so no card is anchor-eligible.
    first = hit[0]
    for i in hit[:5]:
        cells[i].phi_s_deg = 0.0
    with pytest.warns(RfqPhaseInconsistencyWarning) as rec:
        rep = repair_rfq_phases(lat, PROTON.mass, PROTON.charge, 352.21)
    assert [f.index for f in rep] == hit[:5]
    assert any("cannot be anchored out" in str(w.message) for w in rec)
    # raw derived value used, i.e. offset exactly 0
    phi, _ = derived_phases(_demo(), PROTON.mass, PROTON.charge, 352.21)
    assert rep[0].phi_derived_deg == pytest.approx(phi[first], abs=1e-9)


def test_zero_frequency_raises():
    with pytest.raises(ValueError, match="frequency_MHz"):
        derived_phases(_demo(), PROTON.mass, PROTON.charge, 0.0)


def test_lattice_without_rfq_is_handled():
    from linac_gen.core.lattice import Lattice
    from linac_gen.elements.drift import Drift
    lat = Lattice()
    lat.elements.append(Drift("D", 100.0, 10.0))
    phi, valid = derived_phases(lat, PROTON.mass, PROTON.charge, 352.21)
    assert phi.size == 0 and valid.size == 0
    assert inconsistent_phase_cells(
        lat, PROTON.mass, PROTON.charge, 352.21) == []


# ---------------------------------------------------------------- PXIE


@pytest.fixture
def pxie():
    from tests.rfq import ref_loaders as rl
    if not rl.PXIE_DECK.is_file():
        pytest.skip("lebt_plus_rfq example deck not present")
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        lat, _ = parse_tracewin(str(rl.PXIE_DECK))
    return lat


def test_pxie_flags_exactly_the_five_terminator_cards(pxie):
    """Cells 195–199 carry θs = −90 while A10, m, L, dP and the .vane
    geometry all continue their ramp.  Nothing else may be flagged."""
    bad = inconsistent_phase_cells(pxie, H_MINUS.mass, H_MINUS.charge,
                                   162.5)
    # 199 is not derivable (its successor is the exit matcher); it is
    # picked up by the run-extension inside repair_rfq_phases.
    assert [f.index for f in bad] == [195, 196, 197, 198]
    for f in bad:
        assert f.phi_card_deg == pytest.approx(-90.0)
        assert -30.0 < f.phi_derived_deg < -18.0, f.phi_derived_deg
        assert f.A10 > 0.6


def test_pxie_repair_extends_the_run_to_cell_199(pxie):
    with pytest.warns(RfqPhaseInconsistencyWarning):
        rep = repair_rfq_phases(pxie, H_MINUS.mass, H_MINUS.charge, 162.5)
    assert [f.index for f in rep] == [195, 196, 197, 198, 199]
    cells = _cells(pxie)
    for f in rep:
        assert cells[f.index].phi_s_deg == pytest.approx(f.phi_derived_deg)
        assert -30.0 < f.phi_derived_deg < -18.0
    # smooth continuation of cell 194's ramp, not a step
    assert abs(cells[195].phi_s_deg - cells[194].phi_s_deg) < 3.0


def test_pxie_dry_run_reports_without_mutating(pxie):
    before = [c.phi_s_deg for c in _cells(pxie)]
    with pytest.warns(RfqPhaseInconsistencyWarning):
        rep = repair_rfq_phases(pxie, H_MINUS.mass, H_MINUS.charge,
                                162.5, dry_run=True)
    assert len(rep) == 5
    assert [c.phi_s_deg for c in _cells(pxie)] == before


@pytest.mark.slow
def test_pxie_repair_closes_the_energy_gap(pxie):
    """End-to-end: the repaired deck must land on Toutatis's 2093.3 keV.

    Toutatis read the same 203 cards *plus* pxie-rfq.vane (RFQ_GEOM 1),
    so it never saw the −90s.  The card model does, and loses 137.6 keV.
    """
    from linac_gen.core.beam import Beam
    from linac_gen.core.reference import ReferenceParticle
    from linac_gen.core.simulation import Simulation

    def exit_W(lat):
        b = Beam(ref=ReferenceParticle(species=H_MINUS, w_kin=0.029993,
                                       frequency=162.5),
                 n_particles=4, current=0.0)
        b.particles[:] = 0.0
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            Simulation(lat, b, space_charge="off",
                       record_substeps=False).run()
        return b.ref.w_kin * 1e3

    from tests.rfq import ref_loaders as rl
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        base, _ = parse_tracewin(str(rl.PXIE_DECK))
    w_before = exit_W(base)
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        repair_rfq_phases(pxie, H_MINUS.mass, H_MINUS.charge, 162.5)
    w_after = exit_W(pxie)
    # The LEBT+RFQ deck starts upstream of the RFQ, so the absolute
    # numbers differ from the RFQ-only harness; what must hold is that
    # the repair recovers the great majority of the 137.6 keV deficit.
    assert w_after > w_before + 100.0, (w_before, w_after)
