"""The ring benchmark list (benchmarks/ring/cases.yaml) is valid YAML and
every case names its level, milestone and what it checks."""
from pathlib import Path

import pytest

yaml = pytest.importorskip("yaml")

CASES = Path(__file__).resolve().parents[2] / "benchmarks" / "ring" / "cases.yaml"


def test_the_case_list_parses():
    d = yaml.safe_load(CASES.read_text(encoding="utf-8"))
    rows = d["cases"]
    ids = [r["id"] for r in rows]
    assert len(ids) == len(set(ids))
    for r in rows:
        assert {"id", "level", "milestone", "what"} <= set(r), r.get("id")
        assert isinstance(r["what"], str) and r["what"]


def test_the_manuals_case_page_is_current():
    """docs/manual/12_validation/07_ring_cases.md is the list, generated by
    benchmarks/ring/report.py (run it after editing cases.yaml)."""
    import importlib.util
    spec = importlib.util.spec_from_file_location("ring_report", CASES.parent / "report.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    assert mod.PAGE.is_file(), "the case page is missing: python benchmarks/ring/report.py"
    assert mod.PAGE.read_text(encoding="utf-8") == mod.public_page(), \
        "the case page is not current: python benchmarks/ring/report.py"


def test_the_dev_case_list_parses():
    """The cases on private lattices (benchmarks/ring/dev/cases.yaml, left out
    of public releases) parse as the public list does."""
    dev = CASES.parent / "dev" / "cases.yaml"
    if not dev.is_file():
        pytest.skip("no dev cases here (a public release)")
    rows = yaml.safe_load(dev.read_text(encoding="utf-8"))["cases"]
    for r in rows:
        assert {"id", "level", "milestone", "what"} <= set(r), r.get("id")
