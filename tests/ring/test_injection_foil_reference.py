"""Ring mode, milestone M5: the foil against reference code C.

A pencil beam of 800 MeV protons through carbon foils of 380 ug/cm^2 to
20 mg/cm^2 in reference code C (tests/ring/fixtures/refs/
foil_scattering_ref.json, generated by benchmarks/ring/dev/refgen/):

* its multiple scattering as a Monte Carlo of single screened-Rutherford
  scatters: the width of the core — a Gaussian of the central 98 % of the
  projected angles, the definition Highland's formula is fitted to (the rms
  of the central 98 % over 0.9395) — is HELIX's theta0 (Lynch & Dahl's form,
  z^2/beta^2 in the logarithm) within 2 % at 6 and 20 mg/cm^2 (measured
  0.8-1.1 % and 0.3 % narrower) and 7 % at 380 and 600 ug/cm^2 (6.0 % and
  4.7 % narrower: there the formula is extrapolated two orders below the
  thicknesses it was fitted to, x/X0 = 1e-3 to 100).  The distribution is not
  a Gaussian: at 380-600 ug/cm^2 half its central 68 % is 17-20 % narrower
  than theta0, and its single-scattering tail, which HELIX does not model,
  makes its full rms 1.42-1.59 times theta0;
* its full model takes for its multiple scattering Rossi's width
  13.6 MeV/(beta c p) sqrt(x/X0), without Highland's logarithmic term, and
  loses its mean ionization loss with no straggling: HELIX's Bethe mean loss
  is within 5 % of it (its default, the tabulated minimum-ionizing rate, is
  19 % lower at 800 MeV — the floor it is documented as).
"""
from __future__ import annotations

import hashlib
import json
import math
from pathlib import Path

import numpy as np
import pytest

REF = Path(__file__).resolve().parent / "fixtures" / "refs" / "foil_scattering_ref.json"
DATA = json.loads(REF.read_text())
RUNS = {(r["model"], int(r["thickness_ug_cm2"])): r for r in DATA["runs"]}
#: the rms of a Gaussian's central 98 % over its sigma
CENTRAL98 = 0.9395


def _foil(ug, dedx="mip"):
    from linac_gen.ring.injection.foil import FoilSettings, RingFoil
    return RingFoil(FoilSettings(name="f", node=0, material="C", thickness_ug_cm2=float(ug),
                                 straggling="auto", dedx_model=dedx, strip_model="off",
                                 x_min_m=None, x_max_m=None, y_min_m=None, y_max_m=None,
                                 map_bins=(1, 1)), mass_mev=938.27208816)


def test_reference_file_is_the_generated_one():
    manifest = json.loads(REF.with_suffix(".manifest.json").read_text())
    assert manifest["output_sha256"] == hashlib.sha256(REF.read_bytes()).hexdigest()
    assert DATA["kinetic_mev"] == 800.0 and DATA["material"] == "C"


@pytest.mark.parametrize("ug", [380, 600, 6000, 20000])
def test_the_scattering_core_is_highlands_width(ug):
    r = RUNS[("simple", ug)]
    th = _foil(ug).physics(800.0)["theta0"]
    for plane in ("xp", "yp"):
        core = r[plane]["rms_central98"] / CENTRAL98
        assert th == pytest.approx(core, rel=0.07 if ug <= 600 else 0.02), (plane, th, core)
    # the shape: half the central 68 % narrower at thin foils, the tail wider
    half68 = r["xp"]["half_68"]
    if ug <= 600:
        assert 0.78 * th < half68 < 0.87 * th
        assert 1.4 * th < r["xp"]["rms"] < 1.7 * th
    # HELIX's own draw: a Gaussian of rms theta0 (its central 98 % as above)
    f = _foil(ug)
    X = np.zeros((6, 200_000))
    f.cross(X, np.random.default_rng(3), p0c=1463.2960537963617, beta0=0.8418107059,
            kinetic_mev=800.0)
    a = X[1] / (1.0 + X[5])
    lo, hi = np.quantile(a, (0.01, 0.99))
    core = a[(a >= lo) & (a <= hi)]
    assert math.sqrt(np.mean(core * core)) / CENTRAL98 == pytest.approx(th, rel=0.01)


@pytest.mark.parametrize("ug", [380, 600, 6000, 20000])
def test_the_full_models_width_and_loss(ug):
    r = RUNS[("full", ug)]
    x_x0 = ug * 1e-6 / 42.70                           # carbon, X0 42.70 g/cm^2
    beta, p = 0.8418107059, 1463.2960537963617
    rossi = 13.6 / (beta * p) * math.sqrt(x_x0)
    assert r["xp"]["rms_central98"] / CENTRAL98 == pytest.approx(rossi, rel=0.05)
    loss_ref = -r["dE_gev"]["mean"] * 1e3              # MeV
    assert _foil(ug, "bethe").physics(800.0)["mean_loss_mev"] == pytest.approx(loss_ref,
                                                                                rel=0.05)
    assert _foil(ug, "mip").physics(800.0)["mean_loss_mev"] == pytest.approx(0.81 * loss_ref,
                                                                              rel=0.02)
