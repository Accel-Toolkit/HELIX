"""Ring mode, milestone M5: the bump dipole against reference code A.

A thick kicker compiled as a bump magnet of an injection (the "dipole" model:
an exact dipole in a straight frame with hard-edge dipole fringe and pole
faces) tracks the stored particles — crossing it at angles up to 70 mrad —
as reference code A's dipole of the same field, length, fringe and faces
(tests/ring/fixtures/refs/bump_dipole_ref.npz, generated by
benchmarks/ring/dev/refgen/; its manifest beside it).  The comparison goes
through the compiler: the importers' half drift, thin kick, half drift, the
kick k0 = -kick/L, the vertical plane in a frame turned by 90 degrees.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

import numpy as np
import pytest

REF = Path(__file__).resolve().parent / "fixtures" / "refs" / "bump_dipole_ref.npz"
DATA = np.load(REF)
SPECS = {s["id"]: s for s in json.loads(str(DATA["specs_json"]))}
#: round-off: 1e-14 relative, and the positions and zeta to 1e-14 m absolute
#: — the reference updates the position as (pz' - pz)/k0, whose round-off is
#: about 1e-16/|k0| m (2e-15 m at k0 = 0.06 /m), where HELIX writes the same
#: quantity without the difference (measured: 3e-15 m at most)
RTOL = 1e-14
ATOL = np.array([1e-14, 1e-16, 1e-14, 1e-16, 1e-14, 1e-16])[:, None]


def test_reference_file_is_the_generated_one():
    manifest = json.loads(REF.with_suffix(".manifest.json").read_text())
    assert manifest["output_sha256"] == hashlib.sha256(REF.read_bytes()).hexdigest()
    assert sorted(manifest["cases"]) == sorted(SPECS)


def _track(spec):
    from linac_gen.core.lattice import Lattice
    from linac_gen.elements.drift import Drift
    from linac_gen.elements.steerer import Steerer
    from linac_gen.ring.compile import compile_ring, lattice_rigidity
    from linac_gen.ring.kernels.cpu import backend
    from linac_gen.ring.optics import _energy
    from linac_gen.ring.reference import RingReference
    p0c_ev, mass_ev = float(DATA["reference"][0]), float(DATA["reference"][1])
    ref = RingReference(mass=mass_ev * 1e-6, charge=1, p0c=p0c_ev * 1e-6)
    brho = lattice_rigidity("proton", 800.0)
    k = spec["kick"]
    hk, vk = (k, 0.0) if spec["plane"] == "x" else (0.0, k)
    half = spec["length"] * 500.0                         # mm
    lat = Lattice()
    for e in (Drift("k_din", half), Steerer(name="k", by_l=hk * brho, bx_l=vk * brho),
              Drift("k_dout", half)):
        lat.add(e)
    rl = compile_ring(lat, ref, lattice_species="proton", lattice_energy=800.0,
                      bumps={"k": {"plane": spec["plane"], "kick": None, "fint": spec["fint"],
                                   "hgap_m": spec["hgap"], "e1_rad": spec["e1"],
                                   "e2_rad": spec["e2"]}})
    assert len(rl.bumps) == 1 and rl.bumps[0]["k0"] == pytest.approx(-k / spec["length"],
                                                                     rel=1e-15)
    assert rl.length == pytest.approx(spec["length"], rel=1e-15)
    X = np.array(DATA["x_in"], dtype=float, order="C")
    pt, rp, rv = (np.ascontiguousarray(a) for a in _energy(X[5], ref.beta0))
    backend().track_probe(X, pt, rp, rv, *rl.node_table(), 0, rl.n_nodes,
                          np.empty((0, 6, X.shape[1])), False)
    return X


@pytest.mark.parametrize("case", sorted(SPECS))
def test_the_bump_dipole_tracks_as_the_reference(case):
    got = _track(SPECS[case])
    want = DATA[f"x_out_{case}"]
    err = np.abs(got - want)
    assert np.all(err <= ATOL + RTOL * np.abs(want)), (case, float(np.max(err / (
        ATOL + RTOL * np.abs(want)))))
