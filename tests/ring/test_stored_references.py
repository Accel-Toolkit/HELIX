"""The simple Booster's one-turn optics against the stored MAD-X reference.

``tests/ring/fixtures/refs/simple_booster_madx.json`` was generated by a
dev-only script (MAD-X via cpymad, RF voltage zero; its
manifest records the command, MAD-X version and SHA-256 of the deck).  This
test needs no MAD-X, so it runs wherever HELIX does (CI included); the
importer tests in ``tests/io/test_madx_lines.py`` repeat it against a live
MAD-X when cpymad is installed.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

import pytest

FIX = Path(__file__).resolve().parent / "fixtures"
REF = FIX / "refs" / "simple_booster_madx.json"


def _lf_sha256(path: Path) -> str:
    # (a Windows checkout may turn the line ends into CRLF: hash them as LF,
    # as the files were written)
    return hashlib.sha256(path.read_bytes().replace(b"\r\n", b"\n")).hexdigest()


def test_reference_belongs_to_the_committed_deck():
    manifest = json.loads(REF.with_suffix(".manifest.json").read_text())
    deck = FIX / "simple_booster.madx"
    assert manifest["inputs"]["simple_booster.madx"] == _lf_sha256(deck)
    assert manifest["output_sha256"] == _lf_sha256(REF)
    assert manifest["options"]["rf_off"] is True


def test_simple_booster_optics_match_the_stored_madx_reference(tmp_path):
    from linac_gen.io.madx_parser import parse_madx
    from linac_gen.matching.periodic import find_periodic_twiss

    ref_madx = json.loads(REF.read_text())
    text = (FIX / "simple_booster.madx").read_text(encoding="latin-1")
    deck = tmp_path / "simple_booster_rf_off.madx"
    # (RF voltage zero, as in the reference: HELIX's linac RF gap would add a
    # transverse RF focusing term that a ring cavity does not have)
    deck.write_text(text.replace("total_voltage = 0.2;", "total_voltage = 0.0;"))
    lat, meta = parse_madx(str(deck))
    ref = meta["reference"]
    assert sum(e.length for e in lat.elements) / 1000 == pytest.approx(ref_madx["length_m"], abs=1e-9)
    assert ref.beta == pytest.approx(ref_madx["beta0"], rel=1e-15)
    pt = find_periodic_twiss(lat, ref)
    start = ref_madx["start"]
    assert pt["beta_x"] == pytest.approx(start["betx"], abs=1e-9)
    assert pt["beta_y"] == pytest.approx(start["bety"], abs=1e-9)
    assert pt["alpha_x"] == pytest.approx(start["alfx"], abs=1e-9)
    assert pt["alpha_y"] == pytest.approx(start["alfy"], abs=1e-9)
    eta_m = pt["disp_x"] * ref.beta ** 2 * (ref.species.mass + ref.w_kin) * 1e-3
    assert eta_m == pytest.approx(start["dx_delta"], abs=1e-9)
    assert pt["mu_x"] / 360.0 == pytest.approx(ref_madx["q1"] % 1.0, abs=1e-9)
    assert pt["mu_y"] / 360.0 == pytest.approx(ref_madx["q2"] % 1.0, abs=1e-9)
